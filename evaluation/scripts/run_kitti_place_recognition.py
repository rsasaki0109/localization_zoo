#!/usr/bin/env python3
"""Run the KITTI place-recognition benchmark and write its report.

For each sequence: run build/evaluation/place_recognition_benchmark on the raw
Velodyne scans (no ground truth), keep its per-query output under
experiments/results/place_recognition/, then score every sequence with
evaluate_place_recognition.py and render docs/place_recognition_benchmark.md.

Scans can come from any KITTI Odometry tree (dataset/sequences/NN/velodyne),
e.g. one made by fetch_kitti_odometry_sequences.py. Pass --rescore-only to
rebuild the report from the committed per-query files without the scans.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import evaluate_place_recognition as evaluator  # noqa: E402

RAW_DIR = REPO_ROOT / "experiments" / "results" / "place_recognition"
REPORT_JSON = REPO_ROOT / "experiments" / "results" / "kitti_place_recognition.json"
REPORT_MD = REPO_ROOT / "docs" / "place_recognition_benchmark.md"
REPORT_PNG = REPO_ROOT / "docs" / "assets" / "place_recognition_pr.png"
METHOD_NOTES = {
    "scan_context": "[Scan Context](../papers/scan_context/) (IROS 2018): ring x sector max-height "
                    "descriptor, ring-key prefilter (10 candidates), column-shift cosine distance",
    "isc": "Intensity scan context from [ISC-LOAM](../papers/isc_loam/): the same search on "
           "max-intensity cells",
    "dtd": "[DTD](../papers/dtd/) (2025, from-paper): BEV density keypoints, triangle hashing, "
           "SVD verification; score = inlier count",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--kitti-root", type=Path,
                        help="KITTI Odometry root containing sequences/NN/velodyne.")
    parser.add_argument("--sequences", nargs="+", default=["00", "02", "05", "07", "08"])
    parser.add_argument("--binary", type=Path,
                        default=REPO_ROOT / "build" / "evaluation" / "place_recognition_benchmark")
    parser.add_argument("--methods", default="scan_context,isc,dtd")
    parser.add_argument("--exclude-frames", type=int, default=50)
    parser.add_argument("--revisit-radius", type=float, default=4.0)
    parser.add_argument("--skip-existing", action="store_true",
                        help="Keep per-query files that already exist.")
    parser.add_argument("--rescore-only", action="store_true",
                        help="Do not run the binary; score the committed per-query files.")
    return parser.parse_args()


def raw_path(sequence: str) -> Path:
    return RAW_DIR / f"kitti_{sequence}.json"


def gt_path(sequence: str) -> Path:
    return REPO_ROOT / "experiments" / "reference_data" / f"kitti_seq_{sequence}_full_gt.csv"


def run_sequence(args: argparse.Namespace, sequence: str) -> None:
    output = raw_path(sequence)
    if args.skip_existing and output.is_file():
        print(f"[place_recognition] reuse {output.relative_to(REPO_ROOT)}")
        return
    if args.kitti_root is None:
        raise SystemExit("--kitti-root is required unless --rescore-only is set")
    velodyne = args.kitti_root / "sequences" / sequence / "velodyne"
    if not velodyne.is_dir():
        raise SystemExit(f"missing scans: {velodyne}")
    output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [str(args.binary), "--velodyne-dir", str(velodyne), "--output-json", str(output),
         "--methods", args.methods, "--exclude-frames", str(args.exclude_frames)],
        check=True,
    )
    # Keep the committed file free of machine-specific paths.
    payload = json.loads(output.read_text())
    payload["velodyne_dir"] = f"sequences/{sequence}/velodyne"
    output.write_text(json.dumps(payload, separators=(",", ":")) + "\n")


def render_markdown(report: dict) -> str:
    sequences = report["sequences"]
    method_names = sorted({m for s in sequences for m in s["methods"]})
    lines = [
        "# KITTI place-recognition benchmark",
        "",
        "_Generated by `evaluation/scripts/run_kitti_place_recognition.py`._",
        "",
        "Loop-closure descriptors on full KITTI Odometry sequences, scored with the usual "
        "top-1 retrieval protocol. Every scan is queried against all scans at least "
        f"{sequences[0]['exclude_frames']} frames older, then added to the database. A query "
        f"is a *revisit* when a ground-truth position within {report['protocol']['revisit_radius_m']:g} m "
        "exists among those older scans; a prediction is correct when its top-1 match lies within "
        "that radius. Recall counts correct top-1 matches over all revisits, so a revisit whose "
        "best match is wrong is missed at every threshold. The descriptor binary never reads "
        "poses; labels are assigned afterwards from `experiments/reference_data/kitti_seq_NN_full_gt.csv`.",
        "",
        "Methods:",
        "",
    ]
    lines += [f"- `{m}`: {METHOD_NOTES.get(m, m)}" for m in method_names]
    lines += [
        "",
        "F1max is the best F1 over all score thresholds; R@100P is the recall at the highest "
        "threshold with no false positive (0 when the most confident match is wrong); "
        "top-1 is the share of revisits whose top-1 match is correct before any threshold. "
        "Times are single-threaded descriptor and search time per scan, measured on the "
        "machine that produced the per-query files.",
        "",
        "| Sequence | Frames | Revisits | Method | F1max | Precision / recall at F1max | R@100P | Top-1 | ms / scan |",
        "|---|---:|---:|---|---:|---|---:|---:|---:|",
    ]
    for seq in sequences:
        for name in method_names:
            r = seq["methods"].get(name)
            if r is None:
                continue
            lines.append(
                f"| {seq['label']} | {seq['frames']} | {seq['revisit_queries']} | `{name}` | "
                f"{r['f1_max']:.3f} | {r.get('precision_at_f1_max', 0):.3f} / "
                f"{r.get('recall_at_f1_max', 0):.3f} | {r['recall_at_100_precision']:.3f} | "
                f"{r['top1_recall_no_threshold']:.3f} | {r['ms_per_frame']:.1f} |"
            )
    best = []
    for seq in sequences:
        name, result = max(seq["methods"].items(), key=lambda item: item[1]["f1_max"])
        best.append(f"{seq['label']} `{name}` {result['f1_max']:.3f}")
    lines += [
        "",
        "Reading:",
        "",
        "- Best F1max per sequence: " + "; ".join(best) + ".",
        "- KITTI 08 revisits its route mostly in the opposite direction, and there every "
        "method's recall at 100 % precision falls below 0.05; KITTI 07 has one short loop "
        "(97 revisits), so its curves are noisy.",
        "- The DTD port finds almost no correct loops. A scan queried against itself verifies, "
        "but a scan about 1 m later does not: verification fits one SVD to all hash-matched "
        "triangles without outlier rejection. See [`papers/dtd/README.md`](../papers/dtd/README.md).",
        "- Scan Context and ISC share the same search and differ only in the cell value "
        "(max height vs max reflectance), so their gap isolates the descriptor content.",
    ]
    lines += [
        "",
        "![Precision-recall curves](assets/place_recognition_pr.png)",
        "",
        "Reproduce from the committed per-query files (no scans needed):",
        "",
        "```bash",
        "python3 evaluation/scripts/run_kitti_place_recognition.py --rescore-only",
        "```",
        "",
        "Re-run the descriptors (scans from `fetch_kitti_odometry_sequences.py` or a full KITTI copy):",
        "",
        "```bash",
        "cmake --build build --target place_recognition_benchmark",
        "python3 evaluation/scripts/run_kitti_place_recognition.py --kitti-root /path/to/dataset",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    args = parse_args()
    sequences = [s.zfill(2) for s in args.sequences]
    if not args.rescore_only:
        for sequence in sequences:
            run_sequence(args, sequence)
    available = [s for s in sequences if raw_path(s).is_file()]
    if not available:
        raise SystemExit("no per-query files to score")
    scored = [
        evaluator.evaluate(raw_path(s), gt_path(s), f"KITTI {s}", args.revisit_radius)
        for s in available
    ]
    for seq in scored:
        seq["results"] = str(Path(seq["results"]).relative_to(REPO_ROOT))
        seq["gt_csv"] = str(Path(seq["gt_csv"]).relative_to(REPO_ROOT))
    report = {
        "schema_version": 1,
        "generated_by": "evaluation/scripts/run_kitti_place_recognition.py",
        "protocol": {
            "retrieval": "top-1 among frames at least exclude_frames older",
            "revisit_radius_m": args.revisit_radius,
            "true_positive": "predicted match within revisit radius (GT positions)",
            "recall_denominator": "queries that have a GT revisit",
        },
        "sequences": scored,
    }
    REPORT_JSON.write_text(json.dumps(report, indent=1) + "\n")
    evaluator.plot(scored, REPORT_PNG)
    REPORT_MD.write_text(render_markdown(report))
    print(evaluator.markdown(scored), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
