def read(p):return json.loads(p.read_text())
def write(p,v):p.write_text(json.dumps(v,indent=2,allow_nan=False)+'\n')
def git(*a):return subprocess.check_output(['git',*a],cwd=W,text=True).strip()
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def commit(message,paths):
    subprocess.run(['git','add','-f',*map(str,paths)],cwd=W,check=True)
    subprocess.run(['git','diff','--cached','--check'],cwd=W,check=True)
    subprocess.run(['git','commit','-m',message],cwd=W,check=True)


def execute(label,argv):
    stage=R/(label+'_execution');stage.mkdir()
    started=time.time()
    with (stage/'stdout.log').open('xb') as out,(stage/'stderr.log').open('xb') as err:
        result=subprocess.run(argv,cwd=W,env=ENV,stdout=out,stderr=err)
    write(stage/'command.json',dict(command=argv,cwd=str(W),source_commit=git('rev-parse','HEAD'),
         started_unix=started,finished_unix=time.time(),exit_code=result.returncode,
         environment={k:ENV[k] for k in ('OMP_NUM_THREADS','OPENBLAS_NUM_THREADS','PYTHONDONTWRITEBYTECODE')}))
    destination=E/(label+'_execution')
    # Import also writes its own index-command/result files in this directory.
    # Merge them with the outer execution receipt before one lossless archive.
    if destination.exists():
        if label!='import':raise RuntimeError('Unexpected existing execution evidence')
        for item in destination.iterdir():
            target=stage/item.name
            if not item.is_file() or target.exists():raise RuntimeError('Execution receipt collision')
            shutil.copyfile(item,target)
            if sha(item)!=sha(target):raise RuntimeError('Execution copy mismatch')
        shutil.rmtree(destination)
    archival.archive(stage,destination)
    print(label,result.returncode,flush=True)
    if result.returncode:raise RuntimeError(label+' failed: preserve evidence')


